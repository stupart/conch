#!/bin/bash
# Bring seashell's microphone recorder into conch, as conch's own helper.
#
#   scripts/sync-microphone.sh <seashell checkout> [commit]
#
# 2026-11-11, Tyler: "does it mess with my audio or mic and make it crackle or
# anything? does it have the latest from seashell?" conch captured with sox,
# whose CoreAudio driver rewrites the input device's IO buffer size every time
# a capture opens and drops what its 85 ms ring cannot hold. Seashell had
# already replaced sox with a native recorder (AVAudioEngine at the device's
# own rate, its own downmix and resampler, rebuilt across device changes), so
# conch builds that recorder from seashell's source rather than writing
# another: native/macos-microphone.swift, MIT, by the same author.
#
# What changes is its identity and nothing else. conch's copy is "conch
# Microphone" (its own Info.plist, mac-app/helpers/microphone/Info.plist): its
# own Microphone permission at its own stable path, never Seashell's, so a
# seashell release can never ask for conch's microphone again. The four substitutions
# below are the whole difference; everything else is seashell's file at
# $COMMIT, byte for byte, and the generated header names that commit.
#
# Run it to take a newer seashell recorder, then bump ConchHelperProtocol in
# the Info.plist only if the PCM or exit-code contract changed: conch replaces
# the installed copy only then (src/microphone-helper.ts), because macOS asks
# for the permission again whenever it does.
set -euo pipefail

SEASHELL="${1:?usage: scripts/sync-microphone.sh <seashell checkout> [commit]}"
COMMIT="${2:-HEAD}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_ROOT/mac-app/helpers/microphone/conch-microphone.swift"
FILE=native/macos-microphone.swift

full="$(git -C "$SEASHELL" rev-parse --verify "$COMMIT^{commit}")"
source="$(git -C "$SEASHELL" show "$full:$FILE")"
digest="$(git -C "$SEASHELL" show "$full:$FILE" | shasum -a 256 | cut -d' ' -f1)"

renamed="$(printf '%s\n' "$source" | sed \
  -e 's/"SEASHELL_MICROPHONE_RESPONSIBLE"/"CONCH_MICROPHONE_RESPONSIBLE"/' \
  -e 's/Usage: seashell-microphone /Usage: conch-microphone /' \
  -e 's/domain: "SeashellMicrophone"/domain: "ConchMicrophone"/' \
  -e 's/Microphone access is off for Seashell Microphone\. Allow it in System Settings → Privacy \& Security → Microphone, or run: seashell meeting microphone setup/Microphone access is off for conch Microphone. Allow it in System Settings → Privacy \& Security → Microphone./')"

# Each substitution must have landed exactly where it was meant to: a seashell
# change that moves one of these lines has to be looked at, not half-renamed.
for expected in '"CONCH_MICROPHONE_RESPONSIBLE"' 'Usage: conch-microphone ' 'domain: "ConchMicrophone"' 'off for conch Microphone.'; do
  grep -qF "$expected" <<<"$renamed" || { echo "error: $FILE at $full no longer has the line that becomes: $expected" >&2; exit 1; }
done
if grep -nE 'SEASHELL_|seashell-microphone|SeashellMicrophone|seashell meeting' <<<"$renamed" >&2; then
  echo "error: a seashell identity is left in $FILE at $full (above)" >&2
  exit 1
fi

{
  echo "// conch Microphone: seashell's microphone recorder, built as conch's own helper."
  echo "// Generated by scripts/sync-microphone.sh from github.com/stupart/seashell"
  echo "// $FILE at $full"
  echo "// (sha256 $digest), MIT (mac-app/third-party/seashell/LICENSE)."
  echo "// Only its identity differs: the responsibility variable, the usage line, the"
  echo "// error domain and the permission message. Do not edit by hand; run the script."
  echo "//"
  printf '%s\n' "$renamed"
} >"$OUT"
echo "wrote $OUT from seashell $full"
